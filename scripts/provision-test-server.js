/**
 * One-shot: create roles + channels in the dev guild (Dev_Guild / Dev_Discord_Token),
 * then write config/config.test.json with new IDs. Copies stores + settings from config/config.json.
 *
 * Prerequisites: bot invited with Manage Channels, Manage Roles, View channels.
 * Run: npm run provision:test
 */

const fs = require('fs').promises;
const path = require('path');
const { Client, GatewayIntentBits, ChannelType, PermissionFlagsBits } = require('discord.js');
require('dotenv').config({ quiet: true });

const CHANNEL_SPECS = [
    { key: 'restockApprovals', name: 'restock-approvals-va', topic: 'VA approval queue (buttons)' },
    { key: 'restockApprovalsMD', name: 'restock-approvals-md', topic: 'MD approval queue (buttons)' },
    { key: 'localRestockVA', name: 'local-restock-va', topic: 'Approved VA restock alerts' },
    { key: 'localRestockMD', name: 'local-restock-md', topic: 'Approved MD restock alerts' },
    { key: 'restock_in_progress_va', name: 'restock-in-progress-va', topic: '/restock_in_progress_va + past report commands' },
    { key: 'restock_in_progress_md', name: 'restock-in-progress-md', topic: '/restock_in_progress_md + past report commands' },
    { key: 'lookup_va_restocks', name: 'lookup-va-restocks', topic: '/lookup_va_restocks' },
    { key: 'lookup_md_restocks', name: 'lookup-md-restocks', topic: '/lookup_md_restocks' },
];

const ROLE_SPECS = [
    { key: 'admin', name: 'Bot Admin', color: 0xe74c3c },
    { key: 'restockApprovalVA', name: 'Restock Approval — VA', color: 0x3498db },
    { key: 'restockApprovalMD', name: 'Restock Approval — MD', color: 0x9b59b6 },
    { key: 'localRestockVA', name: 'VA Local Restock', color: 0x2ecc71 },
    { key: 'localRestockMD', name: 'MD Local Restock', color: 0x1abc9c },
];

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function main() {
    const token =
        process.env.DISCORD_TOKEN_V2?.trim() ||
        process.env.Dev_Discord_Token?.trim() ||
        process.env.DISCORD_TOKEN?.trim();
    const guildId =
        process.env.GUILD_ID_V2?.trim() ||
        process.env.Dev_Guild?.trim() ||
        process.env.GUILD_ID?.trim();

    if (!token || !guildId) {
        console.error(
            'Missing token and guild: set DISCORD_TOKEN_V2 + GUILD_ID_V2, or Dev_Discord_Token + Dev_Guild, or DISCORD_TOKEN + GUILD_ID in .env'
        );
        process.exit(1);
    }

    const configPath = path.join(__dirname, '../config/config.json');
    const outPath = path.join(__dirname, '../config/config.test.json');

    let base;
    try {
        base = JSON.parse(await fs.readFile(configPath, 'utf8'));
    } catch (e) {
        console.error('Could not read config/config.json:', e.message);
        process.exit(1);
    }

    const client = new Client({
        intents: [GatewayIntentBits.Guilds],
    });

    await client.login(token);
    const guild = await client.guilds.fetch(guildId);
    const guildName = guild.name || guild.id;

    console.log(`\n🔧 Provisioning guild: ${guildName} (${guild.id})\n`);

    const me = await guild.members.fetch(client.user.id).catch(() => null);
    if (!me?.permissions.has(PermissionFlagsBits.ManageChannels | PermissionFlagsBits.ManageRoles)) {
        console.warn('⚠️ Bot may lack Manage Channels + Manage Roles. If creation fails, fix permissions.\n');
    }

    const roleIds = {};
    for (const spec of ROLE_SPECS) {
        await sleep(400);
        const role = await guild.roles.create({
            name: spec.name,
            color: spec.color,
            mentionable: true,
            reason: 'Restock bot test provisioning',
        });
        roleIds[spec.key] = role.id;
        console.log(`✅ Role ${spec.key} → ${role.name} (${role.id})`);
    }

    const channelIds = {};
    let category = null;
    await sleep(300);
    try {
        category = await guild.channels.create({
            name: 'Restock Bot (test)',
            type: ChannelType.GuildCategory,
            reason: 'Test server layout',
        });
        console.log(`\n✅ Category: ${category.name} (${category.id})\n`);
    } catch (e) {
        console.warn('⚠️ Could not create category, using no parent:', e.message);
    }

    for (const spec of CHANNEL_SPECS) {
        await sleep(500);
        const row = await guild.channels.create({
            name: spec.name,
            type: ChannelType.GuildText,
            parent: category?.id ?? null,
            topic: spec.topic,
            reason: 'Restock bot test provisioning',
        });
        channelIds[spec.key] = row.id;
        console.log(`✅ Channel ${spec.key} → #${spec.name} (${row.id})`);
    }

    const channels = {
        _comment: 'Test server channel IDs (generated by provision-test-server.js)',
        restockApprovals: channelIds.restockApprovals,
        restockApprovalsMD: channelIds.restockApprovalsMD,
        localRestockVA: channelIds.localRestockVA,
        localRestockMD: channelIds.localRestockMD,
        restock_in_progress_va: channelIds.restock_in_progress_va,
        restock_in_progress_md: channelIds.restock_in_progress_md,
    };

    const wipVa = channelIds.restock_in_progress_va;
    const wipMd = channelIds.restock_in_progress_md;
    const lookupVa = channelIds.lookup_va_restocks;
    const lookupMd = channelIds.lookup_md_restocks;

    const commandChannels = {
        _comment: 'Slash commands are locked to these channel IDs',
        report_past_restock_va: wipVa,
        report_restock_va: wipVa,
        restock_in_progress_va: wipVa,
        lookup_va_restocks: lookupVa,
        report_past_restock_md: wipMd,
        report_restock_md: wipMd,
        restock_in_progress_md: wipMd,
        lookup_md_restocks: lookupMd,
    };

    const channelNames = {
        _comment: 'Friendly names for wrong-channel errors (optional)',
        [wipVa]: '#restock-in-progress-va',
        [lookupVa]: '#lookup-va-restocks',
        [wipMd]: '#restock-in-progress-md',
        [lookupMd]: '#lookup-md-restocks',
    };

    const out = {
        _comment: 'AUTO-GENERATED by scripts/provision-test-server.js — use for local dev only',
        _how_to_get_ids: base._how_to_get_ids,
        channels,
        commandChannels,
        channelNames,
        roles: {
            _comment: 'Role IDs for this test server',
            ...roleIds,
        },
        stores: base.stores,
        settings: base.settings,
    };

    await fs.writeFile(outPath, JSON.stringify(out, null, 2), 'utf8');

    console.log(`\n✅ Wrote ${path.relative(process.cwd(), outPath)}`);
    console.log(
        '\nNext steps:\n' +
            '  1. Assign yourself the "Bot Admin" role in Discord (Server Settings → Roles).\n' +
            '  2. For local dev, swap config: copy config.test.json over config.json OR symlink.\n' +
            '  3. npm run deploy && npm run dev\n',
    );

    client.destroy();
}

main().catch((err) => {
    console.error('❌', err);
    process.exit(1);
});
